const tremolo = (bass1: readonly [number, number], bass2: readonly [number, number], mel: number): Event[] => {
  const out: Event[] = [E(0, [bass1[0], bass1[1]])];
  for (let i = 1; i < 8; i++) out.push(E(i, [1, mel]));
  out.push(E(8, [bass2[0], bass2[1]]));
  for (let i = 9; i < 16; i++) out.push(E(i, [1, mel]));
  return out;
};

