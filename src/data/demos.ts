const E = (slot: number, ...notes: RawNote[]): Event => [slot, notes];

/** 各和弦的弦位（低到高），扫弦按这个顺序铺 */
const CH: Readonly<Record<string, ReadonlyArray<readonly [number, number]>>> = {
  C: [[5, 3], [4, 2], [3, 0], [2, 1], [1, 0]],
  G: [[6, 3], [5, 2], [4, 0], [3, 0], [2, 0], [1, 3]],
  Am: [[5, 0], [4, 2], [3, 2], [2, 1], [1, 0]],
  F: [[6, 1], [5, 3], [4, 3], [3, 2], [2, 1], [1, 1]],
};

/**
 * 一次扫弦 / 滚奏：弦按 6→1（D）或 1→6（U）依次偏移 spread 秒。
 * spread 是总跨度——13 ms 听成和弦，240 ms 才听得出每根弦。
 */
const strum = (
  chord: string,
  dir: "D" | "U",
  slot: number,
  spread = 0.013,
  vel = 0.95,
  mute = 0,
): Event => {
  const base = CH[chord];
  const notes = dir === "D" ? base : [...base].reverse();
  const step = spread / Math.max(1, notes.length - 1);
  const out: RawNote[] = notes.map(([s, f], i) => {
    const tech = { off: Number((i * step).toFixed(4)), vel: Number((vel - 0.02 * i).toFixed(3)), ...(mute ? { mute } : {}) };
    return [s, f, mute === 2 ? "x" : undefined, tech, undefined] as RawNote;
  });
  return E(slot, ...out);
};

